"""zerot — report renderers.

Produces a Markdown report (the primary deliverable), plus JSON and a
compact text view for tooling / CI.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import List

from . import catalog
from .engine import Finding, ScanResult


def _caret_for(f: Finding) -> str:
    """A line with a caret pointing at the offending column."""
    caret = " " * (f.col - 1) + "^"
    return f"      {caret}"


def _escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace("`", "\\`")


def render_markdown(result: ScanResult) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines: List[str] = []
    lines.append("# Zerot Scan Report")
    lines.append("")
    lines.append(f"- **Generated:** {now}")
    lines.append(f"- **Targets:** {', '.join(result.targets)}")
    lines.append(
        f"- **Files scanned:** {result.files_scanned}  "
        f"**Skipped:** {len(result.files_skipped)}  "
        f"**Findings:** {len(result.findings)}"
    )
    lines.append(f"- **Highest severity:** `{result.max_severity().upper()}`")
    lines.append("")

    # Trojan Source banner
    if result.counts_by_category.get("bidi") or \
            result.counts_by_category.get("bidi_unbalanced"):
        lines.append("> :warning: **Trojan Source risk detected** — bidirectional "
                     "controls can make code display differently from how it executes.")
        lines.append("")

    # Summary by category
    lines.append("## Summary")
    lines.append("")
    lines.append("| Category | Severity | Count |")
    lines.append("| --- | --- | ---: |")
    counts = result.counts_by_category
    for cat_id, (label, sev, _desc) in catalog.CATEGORIES.items():
        n = counts.get(cat_id, 0)
        if n:
            lines.append(f"| {label} | {sev} | {n} |")
    if not counts:
        lines.append("| _none_ | - | 0 |")
    lines.append("")

    # Skipped files
    if result.files_skipped:
        lines.append("## Skipped files")
        lines.append("")
        lines.append("| Path | Reason |")
        lines.append("| --- | --- |")
        for s in result.files_skipped:
            lines.append(f"| `{s['path']}` | {_escape(s['reason'])} |")
        lines.append("")

    # Findings grouped by file
    lines.append("## Findings")
    lines.append("")
    if not result.findings:
        lines.append("_No dangerous characters were detected. :tada_")
        lines.append("")
        return "\n".join(lines)

    by_file: dict = {}
    for f in result.findings:
        by_file.setdefault(f.path, []).append(f)

    for path, flist in by_file.items():
        lines.append(f"### `{path}`")
        lines.append("")
        lines.append("| Line:Col | Code point | Category | Looks like |")
        lines.append("| --- | --- | --- | --- |")
        for f in sorted(flist, key=lambda x: (x.line, x.col)):
            cats = ", ".join(
                catalog.CATEGORIES.get(c, (c, "", ""))[0] for c in f.categories
            )
            looks = f"`{f.looks_like}`" if f.looks_like else "—"
            cp = f"U+{f.cp:04X}"
            lines.append(
                f"| {f.line}:{f.col} | `{cp}` | {cats} | {looks} |"
            )
        # context snippet
        lines.append("")
        lines.append("<details><summary>Context</summary>")
        lines.append("")
        seen = set()
        for f in sorted(flist, key=lambda x: (x.line, x.col)):
            key = (f.line, f.context)
            if key in seen:
                continue
            seen.add(key)
            lines.append(f"L{f.line}: `{_escape(f.context)}`")
            lines.append(_caret_for(f))
            lines.append("")
        lines.append("</details>")
        lines.append("")

    # Legend
    lines.append("## Category legend")
    lines.append("")
    for cat_id, (label, sev, desc) in catalog.CATEGORIES.items():
        lines.append(f"- **{label}** (`{sev}`): {desc}")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("_zerot is **read-only**: it only reports findings and never "
                 "modifies your files. By default, comments and string literals "
                 "are not scanned, since text there (e.g. `printf(\"...\")`) does "
                 "not affect how code executes — use `--scan-strings` to include them._")
    lines.append("")
    lines.append("_Generated by [zerot](https://github.com/YikunWei-dev/zerot)._")
    lines.append("")
    return "\n".join(lines)


_ANSI = {
    "reset": "\x1b[0m", "bold": "\x1b[1m",
    "red": "\x1b[31m", "yellow": "\x1b[33m", "cyan": "\x1b[36m",
    "green": "\x1b[32m",
}


def _sev_color(sev: str) -> str:
    return {"critical": "red", "high": "red",
            "medium": "yellow", "low": "cyan"}.get(sev, "reset")


def render_text(result: ScanResult, color: bool = False) -> str:
    def c(code: str, s: str) -> str:
        if not color:
            return s
        return f"{_ANSI.get(code, '')}{s}{_ANSI['reset']}"

    out: List[str] = []
    n = len(result.findings)
    head = f"zerot: {n} finding(s) across {result.files_scanned} file(s)"
    out.append(c("bold", head) if n else c("green", head))
    for f in sorted(result.findings, key=lambda x: (x.path, x.line, x.col)):
        cats = ",".join(f.categories)
        looks = f" looks_like={f.looks_like!r}" if f.looks_like else ""
        sev = "low"
        for cat in f.categories:
            s = catalog.CATEGORIES.get(cat, ("", "low", ""))[1]
            if catalog.SEVERITY_ORDER[s] > catalog.SEVERITY_ORDER[sev]:
                sev = s
        line = (f"  {f.path}:{f.line}:{f.col} "
                f"{c(_sev_color(sev), 'U+%04X' % f.cp)} "
                f"[{c(_sev_color(sev), cats)}]{looks}")
        out.append(line)
    return "\n".join(out)


def render_json(result: ScanResult) -> str:
    payload = {
        "targets": result.targets,
        "files_scanned": result.files_scanned,
        "files_skipped": result.files_skipped,
        "highest_severity": result.max_severity(),
        "counts_by_category": result.counts_by_category,
        "findings": [f.as_dict() for f in result.findings],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)


def _sarif_level(severity: str) -> str:
    if severity in ("critical", "high"):
        return "error"
    if severity == "medium":
        return "warning"
    return "note"


def render_sarif(result: ScanResult) -> str:
    """Render results in SARIF 2.1.0 for GitHub code scanning / Security tab."""
    from . import __version__

    used_rules: dict = {}
    results = []
    for f in sorted(result.findings, key=lambda x: (x.path, x.line, x.col)):
        for cat in f.categories:
            label, sev, desc = catalog.CATEGORIES.get(
                cat, (cat, "low", ""))
            rid = "zerot." + cat
            if rid not in used_rules:
                used_rules[rid] = {
                    "id": rid,
                    "name": cat,
                    "shortDescription": {"text": label},
                    "fullDescription": {"text": desc},
                    "defaultConfiguration": {"level": _sarif_level(sev)},
                    "helpUri": "https://github.com/YikunWei-dev/zerot#readme",
                }
            msg = "Unicode %s (%s)" % (label, f"U+{f.cp:04X}")
            if f.looks_like:
                msg += " looks like '%s'" % f.looks_like
            results.append({
                "ruleId": rid,
                "level": _sarif_level(sev),
                "message": {"text": msg},
                "locations": [{
                    "physicalLocation": {
                        "artifactLocation": {"uri": f.path},
                        "region": {
                            "startLine": f.line,
                            "startColumn": f.col,
                            "snippet": {"text": f.context},
                        },
                    }
                }],
            })

    sarif = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {
                "driver": {
                    "name": "zerot",
                    "version": __version__,
                    "informationUri": "https://github.com/YikunWei-dev/zerot",
                    "rules": list(used_rules.values()),
                }
            },
            "results": results,
        }],
    }
    return json.dumps(sarif, indent=2, ensure_ascii=False)
